/// Static lookup for KJV red-letter verses (words of Jesus).
/// Keys are "BOOK/CHAPTER/VERSE" using the BibleData 3-letter abbreviations.
/// Covers all 4 Gospels (MAT, MRK, LUK, JHN) + Revelation (REV).
enum RedLetterData {

    // MARK: - Public API

    static func isRedLetter(book: String, chapter: Int, verse: Int) -> Bool {
        redLetterVerses.contains("\(book)/\(chapter)/\(verse)")
    }

    // MARK: - Helpers

    private static func v(_ book: String, _ chapter: Int, _ numbers: [Int]) -> [String] {
        numbers.map { "\(book)/\(chapter)/\($0)" }
    }

    private static func r(_ s: Int, _ e: Int) -> [Int] { Array(s...e) }

    // MARK: - Per-Book Builders

